/** Compact ingredient constructor. cost = GBP at Tesco baseline (whole recipe). */
function ig(
  name: string,
  quantity: number,
  unit: string,
  category: IngredientCategory,
  cost: number,
): Ingredient {
  return { name, quantity, unit, category, estimatedCost: cost };
}

function macros(calories: number, protein: number, carbs: number, fat: number): Macros {
  return { calories, protein, carbs, fat };
}

type RecipeInput = Omit<Recipe, 'estimatedCost' | 'costByShop'>;

/** Derive estimatedCost (sum of ingredients) and per-shop costs. */
function build(input: RecipeInput): Recipe {
  const estimatedCost =
    Math.round(input.ingredients.reduce((s, i) => s + i.estimatedCost, 0) * 100) / 100;
  return { ...input, estimatedCost, costByShop: buildCostByShop(estimatedCost) };
}

